import os
import json
import re
from transformers import AutoTokenizer
from vllm import LLM, SamplingParams
from .parser import parse_args_gen
from configs.rules import RULES
from .utils import apply_mask, extract_generation_from_reasoning, insert_generation_into_code, strip_markdown_fences, build_model_prompt, find_hdl_files, save_generation, is_generated, GENERATION_FAILED

"""
Process the dataset and generate the code
"""


def traverse_dataset(root_dir, model, tokenizer, sampling, args):
    sent = skipped = 0

    for subdir, _, files in os.walk(root_dir):
        if args.debug: print(f"[INFO] Processing directory: {subdir}")
        if args.debug: print(f"[INFO] Files found: {files}")
        modules = find_hdl_files(files, args.hdl)


        if not modules or "mask_idx.json" not in files:
            if args.debug: print(f"[INFO] Skipping {subdir} - missing required files")
            continue
        
        if args.debug and len(modules) > 1:
            print(f"[WARNING] multiple HDL files in {subdir}, picking first: {modules[0]}")

        module_file = os.path.join(subdir, modules[0])  
        mask_file = os.path.join(subdir, "mask_idx.json")

        if args.debug: print(f"[INFO] Modules path: {module_file}")

        with open(module_file, 'r') as f:
            text = f.read()

        with open(mask_file, 'r') as mf:
            mask_lines = json.load(mf)

        base_name = os.path.basename(subdir)

        # Batch containers
        batch_prompts = []
        batch_lines = []
        batch_indices = []
        batch_rules = []

        for rule in mask_lines:
            if rule not in RULES:
                continue

            for i, line in enumerate(mask_lines[rule], start=1):
                # A relaunch only generates what an earlier run left unanswered
                if is_generated(args.output_path, rule, base_name, i, line):
                    skipped += 1
                    continue

                sent += 1
                raw_prompt = apply_mask(text, line, args)
                prompt = build_model_prompt(raw_prompt, tokenizer, args)

                batch_prompts.append(prompt)
                batch_lines.append(line)
                batch_indices.append(i)
                batch_rules.append(rule)

                if len(batch_prompts) == args.batch_size:
                    process_batch(
                        batch_prompts,
                        batch_lines,
                        batch_indices,
                        batch_rules,
                        text,
                        base_name,
                        model,
                        sampling,
                        args,
                    )

                    batch_prompts = []
                    batch_lines = []
                    batch_indices = []
                    batch_rules = []

        # Process remaining
        if batch_prompts:
                process_batch(
                    batch_prompts,
                    batch_lines,
                    batch_indices,
                    batch_rules,
                    text,
                    base_name,
                    model,
                    sampling,
                    args,
                )

    print(f"[INFO] {sent} tasks sent to the model, {skipped} skipped as already generated by an earlier run")


def process_batch(
    batch_prompts,
    batch_lines,
    batch_indices,
    batch_rules,
    text,
    base_name,
    model,
    sampling,
    args,
):

    try:
        outputs = model.generate(
            prompts=batch_prompts,
            sampling_params=sampling,
        )
    except Exception as e:
        # The tasks of a failed batch are still written out, as failed, so they stay in
        # the evaluation's denominator instead of silently dropping out of it. A relaunch
        # tries them again.
        print(f"[ERROR] Batch generation failed, its {len(batch_lines)} tasks are recorded as failed: {e!r}")
        reason = f"Generation failed: {e!r}"
        for line, idx, rule in zip(batch_lines, batch_indices, batch_rules):
            save_generation(
                args.output_path, rule, base_name, idx, args.hdl, reason, reason,
                span=line, finish_reason=GENERATION_FAILED, raw_output=reason,
            )
        return
    

    if args.debug and (len(outputs) != len(batch_prompts)):
        print(f"[ERROR] Batch mismatch: got {len(outputs)} outputs for {len(batch_prompts)} prompts")

    # Iterate per prompt
    for output, line, idx, rule in zip(
        outputs,
        batch_lines,
        batch_indices,
        batch_rules,
    ):
        generations = output.outputs

        for j, gen in enumerate(generations, start=1):
            think, gen_text = extract_generation_from_reasoning(gen.text)

            if gen.finish_reason == "stop":
                if args.debug:
                    print("\n\n[INFO] Generated text:")
                    print(f"[INFO] {gen_text}")
                gen_text = strip_markdown_fences(gen_text)
                filled_code = insert_generation_into_code(text, line, gen_text)

            else:
                reason = f"Generation stopped {gen.finish_reason}"
                if args.debug: print(f"[INFO] {reason}")
                filled_code = reason
                gen_text = reason

            save_dir = save_generation(
                args.output_path, rule, base_name, idx, args.hdl, gen_text, filled_code,
                span=line, finish_reason=gen.finish_reason, reasoning=think, raw_output=gen.text, sample=j,
            )

            if args.debug: print(f"[INFO] save_dir: {save_dir}")
                    
            

if __name__ == "__main__":
    args = parse_args_gen()
    print("[INFO] Args parsed:")
    for arg, value in vars(args).items():
        print(f"[INFO]  {arg}: {value}")
    print("[INFO] Loading model...")
    model = LLM(
        model=args.model,
        trust_remote_code=True,
        gpu_memory_utilization=args.gpu_memory_utilization,
        swap_space=args.swap_space,
        dtype=args.precision,
        tensor_parallel_size=args.tensor_parallel_size,
        max_seq_len_to_capture=args.sequence_length_limit, 
        max_model_len=args.sequence_length_limit
    )

    tokenizer = AutoTokenizer.from_pretrained(args.model, trust_remote_code=True)

    sampling = SamplingParams(
                    temperature=args.temperature,
                    top_p=args.top_p,
                    top_k=args.top_k,
                    max_tokens=args.max_tokens,
                    n=1,
                )
    
    print("[INFO] Generating...")
    traverse_dataset(args.dataset_path, model, tokenizer, sampling, args)

