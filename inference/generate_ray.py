import os
import json
from concurrent.futures import ThreadPoolExecutor, wait, FIRST_COMPLETED
from .parser import parse_args_gen_ray
from openai import OpenAI

from .utils import extract_generation_from_reasoning, insert_generation_into_code, strip_markdown_fences, apply_mask, build_conversation, find_hdl_files, save_generation, is_generated, GENERATION_FAILED
from configs.rules import RULES

"""
Run inference on the model using vLLM and Ray.
"""


def traverse_dataset(root_dir, args):
    sent = skipped = 0

    pool = ThreadPoolExecutor(max_workers=args.batch_size) if args.prompt_mode == "chat" else None
    pending = {}

    for subdir, _, files in os.walk(root_dir):

        modules = find_hdl_files(files, args.hdl)


        if not modules or "mask_idx.json" not in files:
            if args.debug: print(f"Skipping {subdir} - missing required files")
            continue

        if args.debug and len(modules) > 1:
            print(f"[WARNING] multiple HDL files in {subdir}, picking first: {modules[0]}")

        module_file = os.path.join(subdir, modules[0])
        mask_file = os.path.join(subdir, "mask_idx.json")

        with open(module_file, "r") as f:
            text = f.read()

        with open(mask_file, "r") as mf:
            mask_lines = json.load(mf)

        base_name = os.path.basename(subdir)

        batch_raw_prompts = []
        batch_lines = []
        batch_indices = []
        batch_rules = []

        for rule in mask_lines:  # rules guaranteed ordered
            if rule not in RULES:
                continue

            tasks = mask_lines[rule]

            for i, line in enumerate(tasks, start=1):
                # A relaunch only generates what an earlier run left unanswered
                if is_generated(args.output_path, rule, base_name, i, line):
                    skipped += 1
                    continue

                sent += 1
                raw_prompt = apply_mask(text, line, args)

                if pool is not None:
                    pending[pool.submit(generate_chat, raw_prompt, args)] = (
                        line, i, rule, text, base_name
                    )
                    # Hand the next task over as soon as a slot frees up, never in bulk:
                    # this also keeps only args.batch_size file bodies alive at a time
                    if len(pending) >= args.batch_size:
                        collect(pending, args)
                    continue

                batch_raw_prompts.append(raw_prompt)
                batch_lines.append(line)
                batch_indices.append(i)
                batch_rules.append(rule)

                if len(batch_raw_prompts) == args.batch_size:
                    process_batch(
                        batch_raw_prompts,
                        batch_lines,
                        batch_indices,
                        batch_rules,
                        text,
                        base_name,
                        args,
                    )

                    batch_raw_prompts = []
                    batch_lines = []
                    batch_indices = []
                    batch_rules = []

        if batch_raw_prompts:
            process_batch(
                batch_raw_prompts,
                batch_lines,
                batch_indices,
                batch_rules,
                text,
                base_name,
                args,
            )

    while pending:
        collect(pending, args)

    if pool is not None:
        pool.shutdown()

    print(f"[INFO] {sent} tasks sent to the model, {skipped} skipped as already generated by an earlier run")


def collect(pending, args):
    """
    Save every in-flight chat request that has come back, and leave the rest running.
    Mutates pending, so the caller's dict stays the live set of outstanding requests.
    """
    done, _ = wait(pending, return_when=FIRST_COMPLETED)

    for future in done:
        line, idx, rule, text, base_name = pending.pop(future)
        save_output(future.result(), line, idx, rule, text, base_name, args)


def generate_chat(raw_prompt, args):
    """
    Generate one task through the chat endpoint. The server renders the prompt itself, 
    with the model's chat template. Its --reasoning-parser splits the reasoning from the 
    answer.

    """
    try:
        response = client.chat.completions.create(
            model=args.model_name,
            messages=build_conversation(raw_prompt),
            temperature=args.temperature,
            top_p=args.top_p,
            max_tokens=args.max_tokens,
            n=1,
            # Some models delimit their reasoning with special tokens (Gemma 4's <|channel>),
            # which vLLM strips from the text by default, before the parser gets to see them
            extra_body={"skip_special_tokens": False, "top_k": args.top_k},
        )
    except Exception as e:
        return e

    choice = response.choices[0]
    raw_output = choice.message.content or ""
    reasoning = getattr(choice.message, "reasoning", None)

    # A server started without a reasoning parser leaves the reasoning inside the answer
    if reasoning is None:
        reasoning, answer = extract_generation_from_reasoning(raw_output)
    else:
        answer = raw_output

    return reasoning, answer, choice.finish_reason, raw_output


def generate_fim(batch_raw_prompts, args):
    """
    Generate a batch of FIM prompts, which are raw text, through the completions endpoint
    in one request.
    """
    try:
        response = client.completions.create(
            model=args.model_name,
            prompt=batch_raw_prompts,   # list of strings = proper batching
            temperature=args.temperature,
            top_p=args.top_p,
            max_tokens=args.max_tokens,
            n=1,
            # top_k is not part of the OpenAI API, vLLM takes it as an extra field
            extra_body={"top_k": args.top_k},
        )
    except Exception as e:
        return [e] * len(batch_raw_prompts)

    if args.debug and (len(response.choices) != len(batch_raw_prompts)):
        print(f"[ERROR] Batch mismatch: got {len(response.choices)} outputs for {len(batch_raw_prompts)} prompts")

    outputs = []
    for choice in response.choices:
        reasoning, answer = extract_generation_from_reasoning(choice.text)
        outputs.append((reasoning, answer, choice.finish_reason, choice.text))

    return outputs


def process_batch(
    batch_raw_prompts,
    batch_lines,
    batch_indices,
    batch_rules,
    text,
    base_name,
    args,
):
    """
    FIM tasks share a single completions request, so they are still gathered into a batch.
    Chat tasks are streamed through the pool in traverse_dataset instead.
    """

    outputs = generate_fim(batch_raw_prompts, args)

    for output, line, idx, rule in zip(
        outputs,
        batch_lines,
        batch_indices,
        batch_rules,
    ):
        save_output(output, line, idx, rule, text, base_name, args)


def save_output(output, line, idx, rule, text, base_name, args):
    """ Write one finished task out, whether the model answered it or the request failed """

    if isinstance(output, Exception):
        # A failed task is still written out, as failed, so it stays in the
        # evaluation's denominator instead of silently dropping out of it. A relaunch
        # tries it again.
        print(f"[ERROR] Generation failed for rule '{rule}', task {idx}, recorded as failed: {output!r}")
        reason = f"Generation failed: {output!r}"
        save_generation(
            args.output_path, rule, base_name, idx, args.hdl, reason, reason,
            span=line, finish_reason=GENERATION_FAILED, raw_output=reason,
        )
        return

    reasoning, answer, finish_reason, raw_output = output

    gen_text = strip_markdown_fences(answer)
    if args.debug:
        print(f"\n[INFO] Generated text for rule '{rule}', line {line}, task {idx}:")
        print(f"         {gen_text}")
    filled_code = insert_generation_into_code(text, line, gen_text)

    save_generation(
        args.output_path, rule, base_name, idx, args.hdl, gen_text, filled_code,
        span=line, finish_reason=finish_reason, reasoning=reasoning, raw_output=raw_output,
    )


if __name__ == "__main__":

    args = parse_args_gen_ray()
    print("[INFO] Args parsed:")
    for arg, value in vars(args).items():
        print(f"      {arg}: {value}")


    client = OpenAI(
        base_url=f"http://{args.ip}:{args.port}/v1",
        api_key="EMPTY",
        # A reasoning model can take far longer than any fixed limit to write max_tokens
        # tokens, so a request is bounded by the job's time limit instead
        timeout=None,
    )

    traverse_dataset(args.dataset_path, args)
